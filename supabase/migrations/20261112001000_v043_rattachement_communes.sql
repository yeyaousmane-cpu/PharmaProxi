-- v043 — Rattachement des structures à leur arrondissement / commune
--
-- Problème corrigé : l'annuaire des pharmacies et l'annuaire des établissements
-- filtrent sur commune_id. Or 50 pharmacies sur 83 et la quasi-totalité des
-- établissements avaient commune_id NULL, donc toute recherche par
-- arrondissement renvoyait « Aucune pharmacie trouvée avec ces critères ».
--
-- Principe : on ne devine aucune géographie. Le rattachement s'appuie
-- uniquement sur le référentiel de quartiers déjà présent dans `localities`
-- (105 quartiers de Bamako déjà rattachés à leur arrondissement), complété par
-- une table d'alias orthographiques explicite et auditable.
--
-- Retour arrière : la table `geo_commune_backfill` conserve l'ancienne valeur
-- de chaque ligne modifiée. Voir le bloc ROLLBACK en fin de fichier.

begin;

-- 1. Clé de comparaison : minuscules, sans accents, sans ponctuation ni espaces.
--    « Baco-Djicoroni ACI » et « Bacodjicoroni » donnent la même clé.
create or replace function public.geo_key(t text)
returns text
language sql
immutable
parallel safe
set search_path to 'public', 'extensions'
as $$
  select regexp_replace(public.normalize_text(coalesce(t, '')), '[^a-z0-9]', '', 'g')
$$;

comment on function public.geo_key(text) is
  'Clé de rapprochement géographique : normalisée, sans accents ni ponctuation.';

-- 2. Quartiers de Faladié à distinguer strictement (demande explicite : ne pas
--    confondre Faladié-Socoro, Faladié Sema, Faladié Solola et Banankabougou).
--    Banankabougou et Faladié existent déjà dans le référentiel.
insert into public.localities (commune_id, name, kind, source)
select c.id, v.name, 'quartier', 'Découpage de Faladié — recensement SantéProxi v043'
from public.communes c
cross join (values
  ('Faladié Sema'),
  ('Faladié Socoro'),
  ('Faladié Solola')
) as v(name)
where c.name = 'Sixième Arrondissement'
  and not exists (
    select 1 from public.localities l
    where l.commune_id = c.id and public.geo_key(l.name) = public.geo_key(v.name)
  );

-- 3. Alias orthographiques. Chaque ligne est une variante d'écriture réellement
--    rencontrée dans les sources, rattachée à un quartier du référentiel.
create table if not exists public.geo_locality_aliases (
  id          bigint generated by default as identity primary key,
  locality_id uuid not null references public.localities(id) on delete cascade,
  alias_key   text not null,
  note        text,
  created_at  timestamptz not null default now(),
  unique (alias_key, locality_id)
);

alter table public.geo_locality_aliases enable row level security;

drop policy if exists "lecture publique" on public.geo_locality_aliases;
create policy "lecture publique" on public.geo_locality_aliases for select using (true);

drop policy if exists "admin écrit" on public.geo_locality_aliases;
create policy "admin écrit" on public.geo_locality_aliases for all using (public.is_admin());

create index if not exists geo_locality_aliases_key_idx
  on public.geo_locality_aliases (alias_key);

comment on table public.geo_locality_aliases is
  'Variantes orthographiques des quartiers, pour le rattachement des structures. Aucune géographie nouvelle : chaque alias pointe vers un quartier existant.';

insert into public.geo_locality_aliases (locality_id, alias_key, note)
select l.id, public.geo_key(v.alias), v.note
from (values
  -- variantes de graphie
  ('Djoumanzana',      'Doumanzana',           'Graphie courante dans les annuaires'),
  ('Sogoninko',        'Sogoniko',             'Graphie courante dans les annuaires'),
  ('Sébéninkoro',      'Sebenicoro',           'Graphie courante dans les annuaires'),
  ('Sébéninkoro',      'Sebenikoro',           'Graphie courante dans les annuaires'),
  ('Medina-Coura',     'Medine',               'Marché Médine / Médina-Coura'),
  ('Sans-Fils',        'TSF',                  'Quartier dit TSF'),
  ('Faladié Socoro',   'Faladie Sokoro',       'Graphie Sokoro relevée dans le répertoire 2026'),
  -- sous-ensembles nommés d'un quartier existant
  ('Hamdallaye',       'ACI 2000',             'Hamdallaye ACI 2000'),
  ('Sotuba',           'Sotuba ACI',           'Sotuba ACI'),
  ('Bacodjicoroni',    'Baco Djicoroni Golf',  'Secteur Golf de Bacodjicoroni'),
  ('Banconi',          'Banconi Flabougou',    'Secteur de Banconi'),
  ('Banconi',          'Banconi Layebougou',   'Secteur de Banconi'),
  ('Badalabougou',     'Badalabougou Sema',    'Badalabougou SEMA'),
  ('Korofina Nord',    'Korofina',             'Mention sans précision Nord/Sud — même arrondissement')
) as v(loc, alias, note)
join public.localities l on public.geo_key(l.name) = public.geo_key(v.loc)
join public.communes c on c.id = l.commune_id
where c.region_id = (select id from public.regions where name = 'District de Bamako')
on conflict (alias_key, locality_id) do nothing;

-- 4. Résolution d'un texte libre (adresse, quartier, libellé de zone) vers un
--    quartier puis un arrondissement. On retient la clé la plus longue trouvée
--    dans le texte : « Faladié Sema » l'emporte sur « Sema », « Sabalibougou
--    Kourani » sur « Sabalibougou ». La commune n'est renvoyée que si tous les
--    quartiers candidats pour cette clé partagent le même arrondissement.
create or replace function public.resolve_locality(p_text text, p_region uuid)
returns table (commune_id uuid, locality_id uuid, matched_key text)
language sql
stable
set search_path to 'public', 'extensions'
as $$
  with target as (select public.geo_key(p_text) as k),
  cand as (
    select l.id as locality_id, l.commune_id, public.geo_key(l.name) as k
    from public.localities l
    join public.communes c on c.id = l.commune_id
    where c.region_id = p_region and l.name not ilike 'Quartier Démo%'
    union all
    select l.id, l.commune_id, a.alias_key
    from public.geo_locality_aliases a
    join public.localities l on l.id = a.locality_id
    join public.communes c on c.id = l.commune_id
    where c.region_id = p_region
  ),
  hit as (
    select cand.k,
           count(distinct cand.commune_id) as nb_communes,
           count(distinct cand.locality_id) as nb_localities,
           min(cand.commune_id::text) as one_commune,
           min(cand.locality_id::text) as one_locality
    from cand, target
    where target.k <> '' and length(cand.k) >= 4 and position(cand.k in target.k) > 0
    group by cand.k
    order by length(cand.k) desc, cand.k
    limit 1
  )
  select case when nb_communes = 1 then one_commune::uuid end,
         case when nb_localities = 1 then one_locality::uuid end,
         k
  from hit
$$;

comment on function public.resolve_locality(text, uuid) is
  'Rattache un texte d''adresse au quartier et à l''arrondissement du référentiel. Ne renvoie la commune que si le rapprochement est non ambigu.';

-- 5. Journal de rattachement : permet de tout annuler.
create table if not exists public.geo_commune_backfill (
  id              bigint generated by default as identity primary key,
  target_table    text not null,
  row_id          uuid not null,
  old_commune_id  uuid,
  new_commune_id  uuid,
  old_locality_id uuid,
  new_locality_id uuid,
  matched_key     text,
  migration       text not null,
  applied_at      timestamptz not null default now()
);

alter table public.geo_commune_backfill enable row level security;

drop policy if exists "admin lit" on public.geo_commune_backfill;
create policy "admin lit" on public.geo_commune_backfill for select using (public.is_admin());

drop policy if exists "admin écrit" on public.geo_commune_backfill;
create policy "admin écrit" on public.geo_commune_backfill for all using (public.is_admin());

comment on table public.geo_commune_backfill is
  'Journal des rattachements automatiques à une commune. Conserve l''ancienne valeur pour permettre un retour arrière.';

-- 6. Les pharmacies ne sont PAS rattachées automatiquement.
--    Vérifié avant écriture : sur les 50 officines sans arrondissement, 47 sont
--    régionales (il n'existe pas de commune pour leur cercle dans le
--    référentiel) et les 3 officines de Bamako restantes n'ont pour adresse que
--    « Bamako ». Un rapprochement sur le nom produisait un faux positif
--    (« Pharmacie Almamy Lassana Thera » rapprochée du quartier Lassa), donc
--    aucune écriture n'est faite ici.

-- 7. Un doublon révélé par la contrainte d'unicité : « Clinique Périnatale
--    Mohammed VI » existait en deux fiches. On garde celle de source
--    officielle (téléphone + position) et on archive l'autre, renommée pour
--    libérer la clé. Rien n'est supprimé.
insert into public.facility_duplicate_candidates (facility_id, other_id, similarity, decision, decided_at)
values ('a6418b2f-85d5-4175-8e40-595e48a89b62', 'af22a9bd-2b3d-402a-a299-7e7bdddc9b60', 1.0, 'fusionnes', now())
on conflict do nothing;

update public.facility_listings
set name = 'Clinique périnatale Mohammed VI (fiche doublon archivée)',
    is_published = false,
    to_verify = left(concat_ws(' ', to_verify, 'Doublon de la fiche de source officielle du même établissement. Conservée en réserve, migration v043.'), 500),
    updated_at = now()
where id = 'af22a9bd-2b3d-402a-a299-7e7bdddc9b60';

update public.facility_listings
set quarter = coalesce(quarter, 'Sébénikoro'), updated_at = now()
where id = 'a6418b2f-85d5-4175-8e40-595e48a89b62';

-- 8. Rattachement des établissements sans arrondissement, en excluant toute
--    ligne qui entrerait en collision avec une fiche déjà rattachée.
with resolved as (
  select f.id, f.search_name, f.region_id, f.circle_id,
         f.commune_id as old_commune,
         rr.commune_id as new_commune,
         rr.matched_key
  from public.facility_listings f
  cross join lateral public.resolve_locality(
    concat_ws(' ', f.quarter, f.locality, f.address, f.city_label), f.region_id
  ) rr
  where f.commune_id is null and f.region_id is not null and rr.commune_id is not null
),
keep as (
  select r.* from resolved r
  where not exists (
    select 1 from public.facility_listings o
    where o.id <> r.id
      and o.search_name = r.search_name
      and coalesce(o.region_id, '00000000-0000-0000-0000-000000000000') = coalesce(r.region_id, '00000000-0000-0000-0000-000000000000')
      and coalesce(o.circle_id, '00000000-0000-0000-0000-000000000000') = coalesce(r.circle_id, '00000000-0000-0000-0000-000000000000')
      and coalesce(o.commune_id, '00000000-0000-0000-0000-000000000000') = r.new_commune
  )
),
logged as (
  insert into public.geo_commune_backfill
    (target_table, row_id, old_commune_id, new_commune_id, matched_key, migration)
  select 'facility_listings', id, old_commune, new_commune, matched_key, 'v043'
  from keep
  returning row_id, new_commune_id
)
update public.facility_listings f
set commune_id = l.new_commune_id,
    updated_at = now()
from logged l
where f.id = l.row_id;

commit;

